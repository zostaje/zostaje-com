function updateAiLinks(language) {
  const prompt = aiPrompts[language];
  const encodedPrompt = encodeURIComponent(prompt);

  document.querySelector('[data-ai="chatgpt"]').href =
    `https://chatgpt.com/?q=${encodedPrompt}&hints=search`;
  document.querySelector('[data-ai="claude"]').href =
    `https://claude.ai/new?q=${encodedPrompt}`;
  document.querySelector('[data-ai="gemini"]').dataset.prompt = prompt;
}

const originalText = new WeakMap();
const textWalker = document.createTreeWalker(
  document.body,
  NodeFilter.SHOW_TEXT,
  {
    acceptNode(node) {
      const parent = node.parentElement;
      if (
        !parent ||
        ["SCRIPT", "STYLE"].includes(parent.tagName) ||
        !node.nodeValue.trim()
      ) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  },
);

const textNodes = [];
while (textWalker.nextNode()) {
  textNodes.push(textWalker.currentNode);
  originalText.set(textWalker.currentNode, textWalker.currentNode.nodeValue);
}

const normalize = (value) => value.trim().replace(/\s+/g, " ");

function applyLanguage(language) {
  textNodes.forEach((node) => {
    const source = originalText.get(node);
    const key = normalize(source);
    const replacement = language === "en" ? translations[key] : null;
    if (replacement) {
      const leading = source.match(/^\s*/)[0];
      const trailing = source.match(/\s*$/)[0];
      node.nodeValue = `${leading}${replacement}${trailing}`;
    } else {
      node.nodeValue = source;
    }
  });

  document.documentElement.lang = language;
  document.title =
    language === "en"
      ? "Zostaje — finances you can understand"
      : "Zostaje — finanse, które da się zrozumieć";
  document.querySelectorAll(".current-language").forEach((label) => {
    label.textContent = language.toUpperCase();
  });
  document.querySelectorAll(".footer-language-name").forEach((label) => {
    label.textContent = language === "en" ? "English" : "Polski";
  });
  document.querySelector("#email").placeholder =
    language === "en" ? "you@example.com" : "ty@adres.pl";
  document.querySelector('meta[name="description"]').content =
    language === "en"
      ? "Zostaje helps you understand everyday finances and see how much you can safely spend."
      : "Zostaje pomaga zrozumieć codzienne finanse i zobaczyć, ile naprawdę możesz wydać — bez arkuszy i finansowego żargonu.";
  const socialTitle =
    language === "en"
      ? "Zostaje — finances you can understand"
      : "Zostaje — finanse, które da się zrozumieć";
  const socialDescription =
    language === "en"
      ? "See how much you can safely spend today. Zostaje brings spending, plans and upcoming payments into one simple view."
      : "Zobacz, ile naprawdę możesz dziś wydać. Zostaje porządkuje wydatki, plany i nadchodzące płatności w jednym prostym widoku.";
  document.querySelector('meta[property="og:title"]').content = socialTitle;
  document.querySelector('meta[property="og:description"]').content =
    socialDescription;
  document.querySelector('meta[property="og:locale"]').content =
    language === "en" ? "en_US" : "pl_PL";
  document.querySelector('meta[name="twitter:title"]').content = socialTitle;
  document.querySelector('meta[name="twitter:description"]').content =
    socialDescription;
  updateAiLinks(language);
  document
    .querySelector(".menu-toggle")
    .setAttribute(
      "aria-label",
      language === "en" ? "Open menu" : "Otwórz menu",
    );
  document
    .querySelector(".menu-close")
    .setAttribute(
      "aria-label",
      language === "en" ? "Close menu" : "Zamknij menu",
    );
  document
    .querySelector(".footer-socials")
    .setAttribute(
      "aria-label",
      language === "en"
        ? "Social media in footer"
        : "Media społecznościowe w stopce",
    );
  try {
    localStorage.setItem("zostaje-language", language);
  } catch {
    // The page still works when storage is unavailable, for example in a restricted local preview.
  }
  document
    .querySelectorAll(".language-menu")
    .forEach((menu) => menu.removeAttribute("open"));
  document
    .querySelectorAll(".footer-language")
    .forEach((menu) => menu.removeAttribute("open"));
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () =>
    applyLanguage(button.dataset.language),
  );
});

const mobileMenu = document.querySelector("#mobile-menu");
const openMenuButton = document.querySelector(".menu-toggle");
const closeMenuButton = document.querySelector(".menu-close");

function openMenu() {
  mobileMenu.hidden = false;
  requestAnimationFrame(() => mobileMenu.classList.add("is-open"));
  document.body.classList.add("menu-open");
  openMenuButton.setAttribute("aria-expanded", "true");
  closeMenuButton.focus();
}

function closeMenu() {
  mobileMenu.classList.remove("is-open");
  document.body.classList.remove("menu-open");
  openMenuButton.setAttribute("aria-expanded", "false");
  window.setTimeout(() => {
    mobileMenu.hidden = true;
  }, 180);
}

openMenuButton.addEventListener("click", openMenu);
closeMenuButton.addEventListener("click", closeMenu);
mobileMenu
  .querySelectorAll("a")
  .forEach((link) => link.addEventListener("click", closeMenu));

document
  .querySelector(".mobile-language-toggle")
  .addEventListener("click", () => {
    const panel = document.querySelector(".mobile-language-panel");
    panel.hidden = !panel.hidden;
  });

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && !mobileMenu.hidden) closeMenu();
});

